_INV_SBOX = [0] * 256
for _i, _v in enumerate(_SBOX):
    _INV_SBOX[_v] = _i
_RCON = [0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1B,0x36,0x6C,0xD8,0xAB,0x4D]


def _xtime(a):
    a <<= 1
    return (a ^ 0x1B) & 0xFF if a & 0x100 else a


def _mul(a, b):
    out = 0
    while b:
        if b & 1:
            out ^= a
        a = _xtime(a)
        b >>= 1
    return out


def _expand(key):
    nk = len(key) // 4
    nr = nk + 6
    words = [list(key[4 * i:4 * i + 4]) for i in range(nk)]
    for i in range(nk, 4 * (nr + 1)):
        temp = list(words[i - 1])
        if i % nk == 0:
            temp = temp[1:] + temp[:1]
            temp = [_SBOX[b] for b in temp]
            temp[0] ^= _RCON[i // nk - 1]
        elif nk > 6 and i % nk == 4:
            temp = [_SBOX[b] for b in temp]
        words.append([words[i - nk][j] ^ temp[j] for j in range(4)])
    return words, nr


def _decrypt_block(block, words, nr):
    state = [list(block[i::4]) for i in range(4)]  # column major to rows

    def add_round_key(rnd):
        for c in range(4):
            word = words[rnd * 4 + c]
            for r in range(4):
                state[r][c] ^= word[r]

    add_round_key(nr)
    for rnd in range(nr - 1, -1, -1):
        for r in range(1, 4):  # inv shift rows
            state[r] = state[r][-r:] + state[r][:-r]
        for r in range(4):  # inv sub bytes
            state[r] = [_INV_SBOX[b] for b in state[r]]
        add_round_key(rnd)
        if rnd:  # inv mix columns
            for c in range(4):
                col = [state[r][c] for r in range(4)]
                state[0][c] = _mul(col[0], 14) ^ _mul(col[1], 11) ^ _mul(col[2], 13) ^ _mul(col[3], 9)
                state[1][c] = _mul(col[0], 9) ^ _mul(col[1], 14) ^ _mul(col[2], 11) ^ _mul(col[3], 13)
                state[2][c] = _mul(col[0], 13) ^ _mul(col[1], 9) ^ _mul(col[2], 14) ^ _mul(col[3], 11)
                state[3][c] = _mul(col[0], 11) ^ _mul(col[1], 13) ^ _mul(col[2], 9) ^ _mul(col[3], 14)
    return bytes(state[r][c] for c in range(4) for r in range(4))


def decrypt_cbc(key: bytes, iv: bytes, data: bytes) -> bytes:
    if len(key) not in (16, 24, 32):
        raise ValueError("AES key must be 128, 192 or 256 bits")
    if len(iv) != 16 or not data or len(data) % 16:
        raise ValueError("AES-CBC needs a 16 byte IV and whole blocks")
    words, nr = _expand(key)
    out = bytearray()
    previous = iv
    for offset in range(0, len(data), 16):
        block = data[offset:offset + 16]
        plain = _decrypt_block(block, words, nr)
        out += bytes(a ^ b for a, b in zip(plain, previous))
        previous = block
    pad = out[-1]
    if 1 <= pad <= 16 and bytes(out[-pad:]) == bytes([pad]) * pad:
        del out[-pad:]
    return bytes(out)
