"""Minimal AES-CBC decryption, in pure Python and with no dependency.

One provider hands its client an encrypted blob and the key material to open
it, so reading it needs AES-CBC and nothing else: no key is held here, no
secret is stored, and nothing is encrypted. The standard library has PBKDF2 but
no cipher, and the alternative was a native dependency built per architecture
for a plugin that vendors its own dependencies, to decrypt a few kilobytes.

Correctness is checked against the NIST SP 800-38A vectors in the tests rather
than against this provider, because a cipher that is only right for one input
is not right.
"""

